"""Regenerate deterministic Q1.15 coefficient ROMs. Requires Python, no numpy."""
from pathlib import Path
import math

ROOT = Path(__file__).resolve().parents[1]

def q15(x):
    return max(-32768, min(32767, round(x * 32768)))

def constant(x):
    return f"16'sh{x & 65535:04x}"

def main():
    tw = ["`timescale 1ns/1ps", "// Generated by tools/generate_roms.py; Q1.15, nearest-even rounding.",
          "module feature_twiddle_rom(input wire clk,input wire [8:0] addr,",
          "    output reg signed [15:0] re,im);",
          "// Clocked constant case: TD does not synthesize array initial assignments reliably.",
          "always @(posedge clk) begin", "    case (addr)"]
    for k in range(512):
        tw.append(f"        9'd{k}: begin re<={constant(q15(math.cos(2*math.pi*k/1024)))}; im<={constant(q15(-math.sin(2*math.pi*k/1024)))}; end")
    tw += ["        default: begin re<=0; im<=0; end", "    endcase", "end", "endmodule", ""]
    hann = ["`timescale 1ns/1ps", "// Generated periodic Hann window. Q1.15, nearest-even rounding.",
            "module feature_hann_rom(input wire clk,input wire [9:0] addr,",
            "    output reg signed [15:0] value);", "always @(posedge clk) begin", "    case (addr)"]
    for k in range(1024):
        hann.append(f"        10'd{k}: value<={constant(q15(.5*(1-math.cos(2*math.pi*k/1024))))};")
    hann += ["        default: value<=0;", "    endcase", "end", "endmodule", ""]
    (ROOT/"feature_twiddle_rom.v").write_text("\n".join(tw), encoding="ascii")
    (ROOT/"feature_hann_rom.v").write_text("\n".join(hann), encoding="ascii")

if __name__ == "__main__": main()
